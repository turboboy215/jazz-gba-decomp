#!/usr/bin/env python3
"""List the GAX songs in baserom.gba, the code that references them, and the level table's
song per level. Writes docs/songs_generated.md (docs/songs.md is the curated version).

GAX song settings struct (from loveemu's scanner / shinen-gax-python):
  u8 num_channels; u8 pad; u16 step_count, num_patterns, restart_position, master_volume;
  u16 pad; u32 seq_data, inst_data, wave_data; u16 mixing_rate, fx_mixing_rate; u8 num_fx_slots
The song title string '"name" \\xa9 composer' sits in the sequence data just before it.
"""
import bisect, csv, re, struct

d = open("baserom.gba", "rb").read()
B = 0x08000000
RATES = {5735, 9079, 10513, 11469, 13380, 15769, 18158, 21025, 26760, 31537, 36316, 40138, 42049}
LEVEL_TABLE, LEVEL_STRIDE, LEVEL_COUNT = 0x083D39D8, 0x4C, 25
FX_BANK = 0x083D1C5C  # fx_data passed to GAX2_init everywhere


def is_rom(p):
    return B <= p < B + len(d) and p % 4 == 0


songs = {}
for o in range(0, len(d) - 0x40, 4):
    ch, steps, pats, restart, vol, seq, inst, wave, rate, fxrate, fxslots = struct.unpack_from("<Bx4Hxx3L2HB", d, o)
    if not (1 <= ch <= 32) or d[o + 0x1E] or rate not in RATES or not (is_rom(seq) and is_rom(inst) and is_rom(wave)):
        continue
    names = list(re.finditer(rb'"([^"\x00]{1,40})" \xa9 ([ -~]+?)[\x00\x01]', d[max(0, o - 0x3000):o]))
    title, author = (names[-1].group(1).decode(), names[-1].group(2).decode()) if names else ("?", "?")
    songs[o + B] = dict(title=title, author=author, ch=ch, pats=pats, rate=rate)

funcs = sorted(int(r["start"], 16) for r in csv.DictReader(open("decomp/functions.csv")))
refs = {a: [] for a in list(songs) + [FX_BANK]}
for i in range(0, len(d) - 3, 4):
    w = struct.unpack_from("<I", d, i)[0]
    if w in refs and not (LEVEL_TABLE - B <= i < LEVEL_TABLE - B + LEVEL_STRIDE * LEVEL_COUNT):
        refs[w].append("sub_%08X" % funcs[bisect.bisect_right(funcs, i + B) - 1])

out = ["# GAX songs (generated by tools/gax_songs.py)", "",
       "| Settings addr | Internal title | Composer | Ch | Patterns | Rate | Referenced from code |", "|---|---|---|---|---|---|---|"]
for a, s in sorted(songs.items()):
    out.append("| %08X | %s | %s | %d | %d | %d | %s |" % (a, s["title"], s["author"], s["ch"], s["pats"], s["rate"], ", ".join(refs[a]) or "level table only"))
out += ["", "FX bank %08X referenced from: %s" % (FX_BANK, ", ".join(refs[FX_BANK])), "",
        "## Level table %08X (%d x 0x%X bytes)" % (LEVEL_TABLE, LEVEL_COUNT, LEVEL_STRIDE), "",
        "| # | Song | Tileset (+0x14) | Palette (+0x48) | Level data (+0x40) |", "|---|---|---|---|---|"]
for i in range(LEVEL_COUNT):
    w = struct.unpack_from("<19I", d, LEVEL_TABLE - B + i * LEVEL_STRIDE)
    out.append("| %d | %s | %08X | %08X | %08X |" % (i, songs[w[0]]["title"] if w[0] in songs else "(none)", w[5], w[18], w[16]))
open("docs/songs_generated.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
